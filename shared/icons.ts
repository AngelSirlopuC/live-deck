export type IconName = keyof typeof ICON_NODES;

export const ICON_NAMES = Object.keys(ICON_NODES) as [IconName, ...IconName[]];

/** Icon node for a curated name, or undefined for anything else (never trust the caller). */
export function iconNode(name: string): IconNode | undefined {
  return Object.hasOwn(ICON_NODES, name) ? ICON_NODES[name as IconName] : undefined;
}
